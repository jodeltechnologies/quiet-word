"""Build the book-by-book retellings and verify their Scripture coverage."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Preserve these allocations when publishing subsequent batches.
BOOKS = [(39, 'Matthew', 91000, 71), (40, 'Mark', 91071, 35)]
stories = []
for book, name, first_id, count in BOOKS:
    chapters = json.loads((ROOT / 'public' / 'data' / f'{book:02}.json').read_text())['chapters']
    expected = [(c, v) for c, chapter in enumerate(chapters, 1)
                for v in range(1, len(chapter['verses']) + 1)]
    rows = (ROOT / 'source' / f'{name.lower()}-retellings.txt').read_text().splitlines()
    if len(rows) != count:
        raise ValueError(f'{name}: expected {count} allocated studies, got {len(rows)}')
    actual = []
    for offset, line in enumerate(rows):
        ref, title, subtitle, body, lesson, question = line.split('|')
        chapter_text, verses = ref.split(':')
        chapter = int(chapter_text)
        bounds = verses.split('-')
        start, end = int(bounds[0]), int(bounds[-1])
        if not (1 <= chapter <= len(chapters) and 1 <= start <= end <= len(chapters[chapter - 1]['verses'])):
            raise ValueError(f'{name}: invalid reference {ref}')
        actual.extend((chapter, verse) for verse in range(start, end + 1))
        paragraphs = body.split('~')
        if any(not entry.strip() for entry in [title, subtitle, *paragraphs, lesson, question]):
            raise ValueError(f'{name}: missing material at {ref}')
        text = f'{name} {chapter}:{start}' + (f'–{end}' if end != start else '')
        stories.append(dict(id=first_id + offset, title=title, subtitle=subtitle,
                            text=text, chapters=[[book, chapter]], start=start,
                            end=end, kind='story', category=name, story=paragraphs,
                            lesson=lesson, question=question))
    if actual != expected:
        raise ValueError(f'{name}: verse coverage must be complete and in order')
    print(f'{name}: {count} studies, {len(chapters)} chapters, {len(actual)} verses')

ids = [item['id'] for item in stories]
if len(ids) != len(set(ids)) or min(ids) < 91000 or max(ids) > 99999:
    raise ValueError('Invalid stable study ID allocation')
target = ROOT / 'public' / 'gospel-retellings.js'
target.write_text('/* Generated by scripts/build-gospel-retellings.py. */\n'
                  'const gospelRetellings = [\n'
                  + ',\n'.join('  ' + json.dumps(item, ensure_ascii=False) for item in stories)
                  + '\n];\n', encoding='utf-8')
