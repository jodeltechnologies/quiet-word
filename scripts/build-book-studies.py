"""Build the book-by-book studies and verify their Scripture coverage."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Preserve these allocations when publishing subsequent batches.
BOOKS = [
    (8, '1 Samuel', 92000, 33),
    (9, '2 Samuel', 92500, 27),
    (10, '1 Kings', 93000, 27),
    (39, 'Matthew', 91000, 71),
    (40, 'Mark', 91071, 35),
    (41, 'Luke', 91106, 61),
    (42, 'John', 91167, 47),
    (43, 'Acts', 91214, 49),
    (44, 'Romans', 91263, 26),
    (45, '1 Corinthians', 91289, 24),
    (46, '2 Corinthians', 91313, 15),
    (47, 'Galatians', 91328, 11),
    (48, 'Ephesians', 91339, 11),
    (49, 'Philippians', 91350, 7),
    (50, 'Colossians', 91357, 7),
    (51, '1 Thessalonians', 91364, 7),
    (52, '2 Thessalonians', 91371, 4),
    (53, '1 Timothy', 91375, 10),
    (54, '2 Timothy', 91385, 6),
    (55, 'Titus', 91391, 5),
    (56, 'Philemon', 91396, 2),
]
stories = []
for book, name, first_id, count, *published_chapters in BOOKS:
    chapters = json.loads((ROOT / 'public' / 'data' / f'{book:02}.json').read_text())['chapters']
    expected = [(c, v) for c, chapter in enumerate(chapters[:published_chapters[0]] if published_chapters else chapters, 1)
                for v in range(1, len(chapter['verses']) + 1)]
    slug = name.lower().replace(' ', '-')
    suffix = 'retellings' if book < 43 else 'studies'
    rows = (ROOT / 'source' / f'{slug}-{suffix}.txt').read_text().splitlines()
    if len(rows) != count:
        raise ValueError(f'{name}: expected {count} allocated studies, got {len(rows)}')
    actual = []
    for offset, line in enumerate(rows):
        ref, title, subtitle, body, lesson, question = line.split('|')
        match = re.fullmatch(r'(\d+):(\d+)(?:-(?:(\d+):)?(\d+))?', ref)
        if not match:
            raise ValueError(f'{name}: invalid reference {ref}')
        chapter, start = map(int, match.groups()[:2])
        last_chapter = int(match[3] or chapter)
        end = int(match[4] or start)
        if (not 1 <= chapter <= last_chapter <= len(chapters)
                or not 1 <= start <= len(chapters[chapter - 1]['verses'])
                or not 1 <= end <= len(chapters[last_chapter - 1]['verses'])
                or (chapter == last_chapter and start > end)):
            raise ValueError(f'{name}: invalid reference {ref}')
        span = range(chapter, last_chapter + 1)
        for number in span:
            first_verse = start if number == chapter else 1
            last_verse = end if number == last_chapter else len(chapters[number - 1]['verses'])
            actual.extend((number, verse) for verse in range(first_verse, last_verse + 1))
        paragraphs = body.split('~')
        if any(not entry.strip() for entry in [title, subtitle, *paragraphs, lesson, question]):
            raise ValueError(f'{name}: missing material at {ref}')
        text = name + ' ' + ref.replace('-', '–')
        stories.append(dict(id=first_id + offset, title=title, subtitle=subtitle,
                            text=text, chapters=[[book, number] for number in span], start=start,
                            end=end, kind='story', category=name, story=paragraphs,
                            lesson=lesson, question=question))
    if actual != expected:
        raise ValueError(f'{name}: verse coverage must be complete and in order')
    print(f'{name}: {count} studies, {published_chapters[0] if published_chapters else len(chapters)} published chapters, {len(actual)} verses')

ids = [item['id'] for item in stories]
if len(ids) != len(set(ids)) or min(ids) < 91000 or max(ids) > 99999:
    raise ValueError('Invalid stable study ID allocation')
target = ROOT / 'public' / 'book-studies.js'
target.write_text('/* Generated by scripts/build-book-studies.py. */\n'
                  'const bibleBookStudies = [\n'
                  + ',\n'.join('  ' + json.dumps(item, ensure_ascii=False) for item in stories)
                  + '\n];\n', encoding='utf-8')
